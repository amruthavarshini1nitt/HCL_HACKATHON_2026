"""Reusable Streamlit renderers: answers, citations, evidence and original figures/tables."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import streamlit as st

from generation.assistant import AnswerResult
from retrieval.types import EvidenceRecord

KIND_LABEL = {"reported": "Reported finding", "interpretation": "AI interpretation",
              "suggestion": "AI suggestion"}
STATUS_ICON = {"supported": "✅", "partial": "🟡", "unsupported": "❌", "unchecked": "➖"}
BANNER = {
    "abstained": ("warning", "Not enough reliable evidence to answer."),
    "blocked": ("error", "This request was not processed."),
    "error": ("error", "The answer service is unavailable."),
    "partial": ("info", "Partial answer: only parts could be verified against the papers."),
}


def numbered_answer(answer: str, citations: list[dict[str, Any]]) -> str:
    """Replace raw ids like [P001_C0007] with [1], [2] matching the citation list."""
    for n, c in enumerate(citations, start=1):
        answer = answer.replace(f"[{c['source_id']}]", f"**[{n}]**")
    return answer


def citation_text(c: dict[str, Any]) -> str:
    bits = [f"**{c.get('paper_title') or c['paper_id']}**", f"page {c['page_number']}"]
    if c.get("label"):
        bits.append(c["label"])
    elif c.get("element_type") in ("table", "figure", "chart"):
        bits.append(c["element_type"])
    if c.get("section"):
        bits.append(f"section: {c['section']}")
    if c.get("derived_from_vlm"):
        bits.append("🤖 model-generated reading of an image")
    return " · ".join(bits)


def show_asset(path: str | None, caption: str | None = None) -> None:
    if path and Path(path).is_file():
        st.image(path, caption=caption, width="stretch")


def show_evidence(rec: EvidenceRecord, index: int | None = None, nested: bool = False) -> None:
    """Evidence viewer. Use nested=True inside an expander (Streamlit forbids nesting expanders)."""
    head = f"{rec.paper_title or rec.paper_id} · p.{rec.page_number} · {rec.label or rec.element_type}"
    if index is not None:
        head = f"[{index}] {head}"
    box = st.container(border=True) if nested else st.expander(head)
    with box:
        if nested:
            st.markdown(f"**{head}**")
        if rec.injection_flag:
            st.warning("Instruction-like text was found in this source and removed. It is treated as data only.")
        if rec.derived_from_vlm:
            st.caption("🤖 Generated by the vision model from the original image; less certain than author text.")
        st.markdown(rec.content or "_(no text)_")
        if rec.caption:
            st.caption(f"Caption: {rec.caption}")
        if rec.parent_content:
            st.markdown("**Surrounding section text**")
            st.caption(rec.parent_content[:1500])
        show_asset(rec.asset_path, rec.label)
        st.caption(f"id `{rec.source_id}` · section: {rec.section or 'n/a'}")


def render_answer(res: AnswerResult, *, key: str, show_debug: bool = True) -> None:
    """Full answer view: banner, answer, claims, citations, original figures, evidence, debug."""
    if res.status in BANNER:
        level, text = BANNER[res.status]
        getattr(st, level)(text)
    st.markdown(numbered_answer(res.answer, res.citations))

    if res.claims:
        with st.expander(f"Claims and verification ({len(res.claims)})"):
            for c in res.claims:
                ids = ", ".join(f"`{s}`" for s in c.source_ids) or "no source"
                st.markdown(f"{STATUS_ICON.get(c.status, '')} **{KIND_LABEL.get(c.kind, c.kind)}**: {c.text}  \n"
                            f"<small>sources: {ids}</small>", unsafe_allow_html=True)
                for r in c.reasons:
                    st.caption(f"↳ {r}")
            st.caption("✅ supported · 🟡 partially supported · ➖ AI suggestion (not checked against papers)")

    if res.limitations:
        st.markdown("**Limitations and uncertainty**")
        for lim in res.limitations:
            st.markdown(f"- {lim}")

    if res.citations:
        st.markdown("**Sources**")
        for n, c in enumerate(res.citations, start=1):
            st.markdown(f"**[{n}]** {citation_text(c)}")
        figs = [c for c in res.citations if c.get("asset_path") and Path(c["asset_path"]).is_file()]
        if figs:
            st.markdown("**Original figures / tables**")
            cols = st.columns(min(len(figs), 3))
            for i, c in enumerate(figs):
                with cols[i % len(cols)]:
                    show_asset(c["asset_path"], f"{c.get('label') or c['element_type']} · "
                                                f"{c.get('paper_title') or c['paper_id']} p.{c['page_number']}")

    if res.evidence:
        with st.expander(f"Retrieved evidence ({len(res.evidence)})"):
            for i, rec in enumerate(res.evidence, start=1):
                show_evidence(rec, i, nested=True)

    if show_debug:
        with st.expander("Debug: query refinement, sufficiency, timings"):
            if res.refined:
                st.markdown("**Refined query**")
                st.json(res.refined.model_dump())
            if res.sufficiency:
                st.markdown("**Evidence sufficiency**")
                st.json({"level": res.sufficiency.level, "reasons": res.sufficiency.reasons,
                         "missing": res.sufficiency.missing, "metrics": res.sufficiency.metrics})
            st.markdown("**Latency (seconds)**")
            st.json({k: round(v, 3) for k, v in res.timings.items()})
            st.markdown("**Pipeline details**")
            st.code(json.dumps(res.debug, indent=2, default=str)[:4000], language="json")


def friendly_error(e: Exception) -> str:
    """User-safe message for unexpected exceptions (details go to the log, not the UI)."""
    import logging
    logging.getLogger("ui").exception("unexpected UI error")
    return "Something went wrong while processing this request. Please try again."


def clean_filename(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name)
